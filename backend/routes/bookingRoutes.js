const express = require("express");
const { protect, authorize } = require("../middleware/authMiddleware");
const { createBooking, myBookings, providerBookings, allBookings, getBooking, changeStatus, cancelBooking, provideEstimate, addMaterials, getBookedSlots, downloadInvoice, previewInvoice } = require("../controllers/bookingController");
const router = express.Router();
router.use(protect);
router.post("/", authorize("customer", "provider", "admin"), createBooking);
router.get("/my", authorize("customer", "provider", "admin"), myBookings);
router.get("/provider", authorize("provider"), providerBookings);
router.get("/", authorize("admin"), allBookings);
router.get("/provider/:providerId/slots", authorize("customer", "provider", "admin"), getBookedSlots);
router.get("/:id", getBooking);
router.get("/:id/invoice", downloadInvoice);
router.get("/:id/invoice/preview", previewInvoice);
router.put("/:id/status", authorize("provider", "admin", "customer"), changeStatus);
router.put("/:id/estimate", authorize("provider"), provideEstimate);
router.put("/:id/materials", authorize("provider"), addMaterials);
router.put("/:id/cancel", authorize("customer", "provider", "admin"), cancelBooking);
router.delete("/:id", authorize("customer", "provider", "admin"), cancelBooking);
module.exports = router;
